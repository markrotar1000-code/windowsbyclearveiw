import assert from 'node:assert/strict';
import { createD1 } from './_lib/d1-sqlite.mjs';
import * as quotes from '../functions/internal/api/quotes/index.js';
import * as quote from '../functions/internal/api/quotes/[id].js';
import * as responses from '../functions/internal/api/supplier-responses.js';
import { publicQuote } from '../functions/internal/_lib/quote-signing.mjs';
import { cleanProductSpecs, readProductSpecs } from '../functions/internal/_lib/supplier-specs.mjs';
const env = { QUOTES_DB: createD1({ schemaFiles: ['internal/db/schema.sql'] }) };
const call = async (fn, method, body, params = {}, query = '') => {
  const r = await fn({ env, params, request: new Request(`https://example.test/internal/api/test${query}`, { method, headers: { 'content-type': 'application/json' }, body: body === undefined ? undefined : JSON.stringify(body) }) });
  return { status: r.status, data: await r.json() };
};
assert.deepEqual(cleanProductSpecs({ series: ' Test ', rogue: 'ignored' }), { series: 'Test' });
assert.throws(() => cleanProductSpecs({ handing: {} }));
const customer = { name: 'Supplier audit test', phone: '5550100100' };
const item = { label: 'Slider', quantity: 1, unitPriceCents: 100, productSpecs: { manufacturer: 'Test brand', series: 'Series X', handing: 'XO viewed from outside' }, measurements: [{ width: '36', height: '48', kind: 'unit', productSpecs: { glass: 'Specified low-e package' } }] };
const created = await call(quotes.onRequestPost, 'POST', { customer, items: [item] }); assert.equal(created.status, 201);
const id = created.data.id;
const loaded = await call(quote.onRequestGet, 'GET', undefined, { id });
assert.equal(readProductSpecs(loaded.data.items[0]).series, 'Series X');
assert.equal(JSON.parse(loaded.data.items[0].measurements_json)[0].productSpecs.glass, 'Specified low-e package');
assert.ok(!JSON.stringify(publicQuote(loaded.data.quote, loaded.data.items)).includes('Series X'), 'internal options do not leak through customer whitelist');
const state = await call(responses.onRequestGet, 'GET', undefined, {}, `?quoteId=${id}`);
const response = { quoteId: id, sourceHash: state.data.sourceHash, supplier: 'Test supplier', reference: 'RFQ-TEST', amountCents: 45000, leadTime: '3 weeks', notes: 'Sample response only' };
assert.equal((await call(responses.onRequestPost, 'POST', response)).status, 201);
assert.equal((await call(responses.onRequestGet, 'GET', undefined, {}, `?quoteId=${id}`)).data.responses[0].current, true);
await call(quote.onRequestPut, 'PUT', { customer, expectedRevision: loaded.data.quote.revision, items: [{ ...item, productSpecs: { series: 'Series Y' } }] }, { id });
const changed = await call(responses.onRequestGet, 'GET', undefined, {}, `?quoteId=${id}`);
assert.equal(changed.data.responses[0].current, false);
assert.equal((await call(responses.onRequestPost, 'POST', response)).status, 409, 'stale supplier version cannot silently attach to current request');
assert.equal((await call(responses.onRequestPost, 'POST', { ...response, sourceHash: changed.data.sourceHash, amountCents: -1 })).status, 400);
console.log('PASS: bounded supplier fields, per-opening overrides, privacy whitelist, append-only supplier responses and specification version mismatch');
