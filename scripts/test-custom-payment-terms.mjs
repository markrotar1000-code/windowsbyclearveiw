import { renderContractTerms } from '../src/lib/render-contract-terms.mjs';
const db=createD1({schemaFiles:['internal/db/schema.sql']});
const env={QUOTES_DB:db,ASSETS:{fetch:async()=>new Response('',{status:404})}};
const base={customer:{name:'Terms test',phone:'3605550100'},items:[{label:'Window',quantity:1,unitPriceCents:100000}]};
const custom='A deposit of 30% is due upon signing. The remaining 70% is due upon completion.';
async function call(fn,method,input,params={}) { const r=await fn({env,params,request:new Request('https://example.test/internal/api/test',{method,headers:{'content-type':'application/json'},body:JSON.stringify(input)})});return {status:r.status,body:await r.json()}; }
const created=await call(quotes.onRequestPost,'POST',{...base,customPaymentTerms:custom});assert.equal(created.status,201);
const id=created.body.id;
const read=()=>db.raw.prepare('SELECT * FROM quotes WHERE id=?').get(id);
assert.equal(read().custom_payment_terms,custom);
assert.equal(publicQuote(read(),[]).customPaymentTerms,custom);
const el={dataset:{term:'paymentTerms'},textContent:''};renderContractTerms({querySelectorAll:()=>[el]},contractTerms,custom);assert.equal(el.textContent,custom);
renderContractTerms({querySelectorAll:()=>[el]},contractTerms,'');assert.equal(el.textContent,contractTerms.paymentTerms);
const standard=await call(quotes.onRequestPost,'POST',base);assert.equal(db.raw.prepare('SELECT custom_payment_terms FROM quotes WHERE id=?').get(standard.body.id).custom_payment_terms,'');
const first=await customerDocumentBytes(env,{quote:read(),items:[]});
await call(share.onRequestPost,'POST',{quoteId:id});
assert.equal((await call(byId.onRequestPut,'PUT',{...base,customPaymentTerms:custom+' Credit all payments.'},{id})).status,200);
assert.equal(db.raw.prepare('SELECT COUNT(*) n FROM quote_sign_links WHERE quote_id=? AND revoked_at IS NULL').get(id).n,0);
assert.notEqual((await customerDocumentBytes(env,{quote:read(),items:[]})).version,first.version);
assert.equal((await call(byId.onRequestPut,'PUT',base,{id})).status,200);assert.equal(read().custom_payment_terms,custom+' Credit all payments.');
assert.equal((await call(byId.onRequestPut,'PUT',{...base,customPaymentTerms:''},{id})).status,200);assert.equal(read().custom_payment_terms,'');
assert.equal((await call(byId.onRequestPut,'PUT',{...base,customPaymentTerms:'x'.repeat(2001)},{id})).status,400);
assert.equal((await call(byId.onRequestPut,'PUT',{...base,customPaymentTerms:custom},{id})).status,200);
db.raw.prepare("UPDATE quotes SET status='finalized',signature_name='Test' WHERE id=?").run(id);
const frozen=await freezeSignedQuote(env,id);assert.equal(JSON.parse(frozen.snapshot_json).terms.paymentTerms,custom);
assert.equal((await call(byId.onRequestPut,'PUT',{...base,customPaymentTerms:'changed'},{id})).status,409);
assert.equal((await freezeSignedQuote(env,id)).sha256,frozen.sha256);
console.log('PASS custom terms: isolated, rendered safely, versioned, revokes links, clears, validates, freezes signed terms');
